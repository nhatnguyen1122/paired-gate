# Source this file to point both SkillOpt roles at the Mistral API.
# Requires MISTRAL_API_KEY in the environment (never commit the key).
: "${MISTRAL_API_KEY:?set MISTRAL_API_KEY first}"
export OPTIMIZER_OPENAI_COMPATIBLE_BASE_URL=https://api.mistral.ai/v1
export TARGET_OPENAI_COMPATIBLE_BASE_URL=https://api.mistral.ai/v1
export OPTIMIZER_OPENAI_COMPATIBLE_API_KEY="$MISTRAL_API_KEY"
export TARGET_OPENAI_COMPATIBLE_API_KEY="$MISTRAL_API_KEY"
export OPTIMIZER_OPENAI_COMPATIBLE_MODEL="${OPTIMIZER_MODEL:-mistral-large-latest}"
export TARGET_OPENAI_COMPATIBLE_MODEL="${TARGET_MODEL:-ministral-8b-latest}"
export OPTIMIZER_OPENAI_COMPATIBLE_TEMPERATURE=0.7
export TARGET_OPENAI_COMPATIBLE_TEMPERATURE=0.7
export TARGET_OPENAI_COMPATIBLE_MAX_TOKENS=1024
export OPTIMIZER_OPENAI_COMPATIBLE_MAX_TOKENS=8000
# Mistral Large 4 always thinks; "none" is rejected, so use the cheapest level.
export OPTIMIZER_OPENAI_COMPATIBLE_REASONING_EFFORT="${OPTIMIZER_REASONING_EFFORT:-low}"
export OPTIMIZER_DEPLOYMENT="$OPTIMIZER_OPENAI_COMPATIBLE_MODEL"
export TARGET_DEPLOYMENT="$TARGET_OPENAI_COMPATIBLE_MODEL"
export SKILLOPT_MAX_USD="${SKILLOPT_MAX_USD:-10}"
export SKILLOPT_MAX_CONCURRENCY="${SKILLOPT_MAX_CONCURRENCY:-8}"
export SKILLOPT_LLM_DIR="${SKILLOPT_LLM_DIR:-$(pwd)/.llm_cache}"
